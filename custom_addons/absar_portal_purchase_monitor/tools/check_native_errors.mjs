/** Actual formatter regressions; does not mount Odoo/OWL. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../static/src/js/native_errors.js', import.meta.url), 'utf8');
const { describePurchaseError } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const cause = new Error('There is no debug context available in the current environment.');
const wrapper = new Error('An error occurred in the owl lifecycle', {cause});
const info = describePurchaseError(wrapper);
assert.ok(info.message.includes(cause.message));
assert.ok(info.message.includes(wrapper.message));
assert.ok(info.details.includes(cause.message));
const rpc = describePurchaseError({message:'RPC_ERROR', data:{message:'Purchase access denied',debug:'server traceback'}});
assert.equal(rpc.message, 'Purchase access denied');
assert.equal(rpc.details, 'server traceback');
assert.equal(describePurchaseError(null).message, 'Purchase could not start.');
const cyclic = {message:'cyclic'};cyclic.cause=cyclic;
assert.equal(describePurchaseError(cyclic).message,'cyclic');
assert.equal(describePurchaseError('literal').message,'literal');
const workspace = readFileSync(new URL('../static/src/js/native_workspace.js', import.meta.url), 'utf8');
assert.ok(workspace.includes('useOwnDebugContext({ categories: ["default"] });'));
assert.ok(!workspace.includes('throw error;'));
assert.ok(!workspace.includes('innerHTML'));
console.log('12 native startup/error regression checks passed; live OWL mounting not exercised.');
